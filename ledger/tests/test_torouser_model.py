"""
Unit tests for ToroUser unmanaged model and authentication integration.
Verifies ToroUser mapping to toro_core.users, ToroUserManager helpers,
role-based permissions, and foreign-key integrity from Ledger models.
"""

from uuid import uuid4
from django.contrib.auth import get_user_model
from django.db import connection, transaction
from django.test import TestCase

from ledger.models import EntityModel, EntityManagementModel, BankAccountModel


class ToroUserModelTests(TestCase):
    def setUp(self) -> None:
        self.User = get_user_model()
        self.test_email = f"test_user_{uuid4().hex[:8]}@example.com"
        self.test_password = "SecurePassword123!"

    def test_torouser_mapping_and_defaults(self) -> None:
        """Verifies ToroUser uses toro_core.users table and unmanaged setting."""
        self.assertEqual(self.User._meta.db_table, '"toro_core"."users"')
        self.assertFalse(self.User._meta.managed)
        self.assertEqual(self.User.USERNAME_FIELD, "email")

    def test_create_user_with_autogenerated_entity(self) -> None:
        """Verifies create_user generates a valid entity_id in toro_core.entities."""
        user = self.User.objects.create_user(
            email=self.test_email,
            password=self.test_password,
            full_name="Test Accountant",
            role="member",
        )
        self.assertIsNotNone(user.id)
        self.assertIsNotNone(user.entity_id)
        self.assertEqual(user.email, self.test_email.lower())
        self.assertTrue(user.check_password(self.test_password))
        self.assertEqual(user.role, "member")
        self.assertFalse(user.is_staff)
        self.assertFalse(user.is_superuser)

        # Verify entity_id actually exists in toro_core.entities
        with connection.cursor() as cur:
            cur.execute("SELECT id FROM toro_core.entities WHERE id = %s", [user.entity_id])
            self.assertIsNotNone(cur.fetchone())

    def test_create_user_ignores_legacy_username_kwarg(self) -> None:
        """Verifies create_user silently discards username kwarg from legacy tests."""
        user = self.User.objects.create_user(
            username="legacy_ignored",
            email=f"legacy_{uuid4().hex[:8]}@example.com",
            password="pass",
        )
        self.assertFalse(hasattr(user, "username"))
        self.assertTrue(user.is_active)

    def test_create_superuser(self) -> None:
        """Verifies create_superuser assigns owner role and superuser/staff privileges."""
        admin_email = f"admin_{uuid4().hex[:8]}@example.com"
        superuser = self.User.objects.create_superuser(
            email=admin_email,
            password="AdminPassword123!",
        )
        self.assertEqual(superuser.role, "owner")
        self.assertTrue(superuser.is_staff)
        self.assertTrue(superuser.is_superuser)
        self.assertTrue(superuser.has_perm("any.permission"))
        self.assertTrue(superuser.has_module_perms("ledger"))

    def test_role_based_permissions(self) -> None:
        """Verifies staff and superuser flags map correctly to roles."""
        # Member role
        member = self.User.objects.create_user(
            email=f"member_{uuid4().hex[:8]}@example.com",
            role="member",
        )
        self.assertFalse(member.is_staff)
        self.assertFalse(member.is_superuser)
        self.assertFalse(member.has_perm("any.perm"))

        # Admin role
        admin = self.User.objects.create_user(
            email=f"admin_role_{uuid4().hex[:8]}@example.com",
            role="admin",
        )
        self.assertTrue(admin.is_staff)
        self.assertFalse(admin.is_superuser)
        self.assertTrue(admin.has_perm("any.perm"))

        # Inactive admin
        admin.is_active = False
        self.assertFalse(admin.has_perm("any.perm"))

    def test_entity_model_admin_foreign_key(self) -> None:
        """Verifies EntityModel.admin ForeignKey links to ToroUser UUID primary key."""
        admin_user = self.User.objects.create_user(
            email=f"entity_admin_{uuid4().hex[:8]}@example.com",
            role="admin",
        )
        entity = EntityModel.add_root(
            name=f"Test Entity {uuid4().hex[:6]}",
            admin=admin_user,
            currency="USD",
        )
        self.assertEqual(entity.admin, admin_user)
        self.assertEqual(entity.admin_id, admin_user.id)

        # Reverse relation
        entities = list(admin_user.admin_of.all())
        self.assertIn(entity, entities)

    def test_entity_management_model_user_foreign_key(self) -> None:
        """Verifies EntityManagementModel.user ForeignKey links to ToroUser UUID."""
        owner = self.User.objects.create_user(
            email=f"owner_{uuid4().hex[:8]}@example.com",
            role="owner",
        )
        manager = self.User.objects.create_user(
            email=f"manager_{uuid4().hex[:8]}@example.com",
            role="member",
        )
        entity = EntityModel.add_root(
            name=f"Managed Entity {uuid4().hex[:6]}",
            admin=owner,
            currency="USD",
        )
        mgmt = EntityManagementModel.objects.create(
            entity=entity,
            user=manager,
            permission_level="read",
        )
        self.assertEqual(mgmt.user, manager)
        self.assertEqual(mgmt.user_id, manager.id)

        # Reverse relation
        permissions = list(manager.entity_permissions.all())
        self.assertIn(mgmt, permissions)
